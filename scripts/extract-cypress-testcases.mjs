import ExcelJS from 'exceljs';
import fs from 'node:fs';
import path from 'node:path';

const workbookPath = process.env.TESTCASE_XLSX || 'd:\\TestCase_CarRentalSystem_Full_Detailed_2026-05-20.xlsx';
const repoRoot = process.cwd();
const fixturePath = path.join(repoRoot, 'cypress', 'fixtures', 'testcase-matrix.json');
const excelSpecDir = path.join(repoRoot, 'cypress', 'e2e', 'excel');

const slugify = (value) => value
  .toLowerCase()
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '');

const cellText = (cell) => {
  if (!cell) return '';
  if (cell.text) return String(cell.text).trim();
  const value = cell.value;
  if (value == null) return '';
  if (typeof value === 'object') {
    if (value.text) return String(value.text).trim();
    if (Array.isArray(value.richText)) return value.richText.map((part) => part.text || '').join('').trim();
    if (value.result != null) return String(value.result).trim();
  }
  return String(value).trim();
};

const parseNote = (note) => {
  const result = {};
  for (const part of String(note || '').split('|')) {
    const [rawKey, ...rawValue] = part.split(':');
    const key = rawKey?.trim();
    const value = rawValue.join(':').trim();
    if (key && value) result[key] = value;
  }
  return result;
};

const workbook = new ExcelJS.Workbook();
await workbook.xlsx.readFile(workbookPath);

const modules = [];
const cases = [];

for (const ws of workbook.worksheets.filter((sheet) => /^MD\d+/.test(sheet.name))) {
  const moduleCode = ws.name.match(/^(MD\d+)/)?.[1];
  const moduleName = cellText(ws.getRow(4).getCell(2)) || ws.name;
  const requirement = cellText(ws.getRow(5).getCell(2));
  const moduleCases = [];

  for (let rowIndex = 1; rowIndex <= ws.rowCount; rowIndex += 1) {
    const row = ws.getRow(rowIndex);
    const id = cellText(row.getCell(1));
    if (!/^TC\d{3}$/.test(id)) continue;

    const note = cellText(row.getCell(7));
    const parsedNote = parseNote(note);
    const testCase = {
      id,
      numericId: Number(id.replace('TC', '')),
      moduleCode,
      moduleName,
      requirement,
      sheetName: ws.name,
      title: cellText(row.getCell(2)),
      steps: cellText(row.getCell(3)),
      expected: cellText(row.getCell(4)),
      role: parsedNote.Role || '',
      priority: parsedNote.Priority || 'P1',
      source: parsedNote.Source || '',
      routeApi: parsedNote['Route/API'] || '',
      row: rowIndex,
    };

    cases.push(testCase);
    moduleCases.push(testCase);
  }

  modules.push({
    code: moduleCode,
    name: moduleName,
    sheetName: ws.name,
    requirement,
    caseCount: moduleCases.length,
    firstCaseId: moduleCases[0]?.id,
    lastCaseId: moduleCases.at(-1)?.id,
  });
}

cases.sort((a, b) => a.numericId - b.numericId);

const expectedIds = Array.from({ length: 525 }, (_, index) => `TC${String(index + 1).padStart(3, '0')}`);
const actualIds = cases.map((testCase) => testCase.id);
const missingIds = expectedIds.filter((id) => !actualIds.includes(id));
const duplicateIds = actualIds.filter((id, index) => actualIds.indexOf(id) !== index);

if (cases.length !== 525 || missingIds.length || duplicateIds.length) {
  throw new Error(`Expected 525 unique test cases TC001-TC525, found ${cases.length}. Missing=${missingIds.join(',')} Duplicates=${duplicateIds.join(',')}`);
}

const matrix = {
  sourceWorkbook: workbookPath,
  generatedAtUtc: new Date().toISOString(),
  totalCases: cases.length,
  modules,
  cases,
};

fs.mkdirSync(path.dirname(fixturePath), { recursive: true });
fs.writeFileSync(fixturePath, `${JSON.stringify(matrix, null, 2)}\n`, 'utf8');

fs.rmSync(excelSpecDir, { recursive: true, force: true });
fs.mkdirSync(excelSpecDir, { recursive: true });

const guardSpec = `/* eslint-disable no-undef */\n// Generated by scripts/extract-cypress-testcases.mjs. Do not edit manually.\n\nimport matrix from '../../fixtures/testcase-matrix.json';\n\nconst expectedIds = Array.from({ length: 525 }, (_, index) => \`TC\${String(index + 1).padStart(3, '0')}\`);\n\ndescribe('Excel workbook traceability guard', () => {\n  it('implements exactly TC001-TC525 from the workbook fixture', () => {\n    const ids = matrix.cases.map((testCase) => testCase.id);\n    expect(matrix.totalCases).to.eq(525);\n    expect(ids).to.deep.eq(expectedIds);\n    expect(new Set(ids).size).to.eq(525);\n    expect(matrix.modules).to.have.length(25);\n    matrix.modules.forEach((module) => expect(module.caseCount, module.code).to.eq(21));\n  });\n});\n`;
fs.writeFileSync(path.join(excelSpecDir, '00-workbook-traceability.cy.js'), guardSpec, 'utf8');

for (const module of modules) {
  const suffix = slugify(module.name.replace(/^MD\d+\s*-\s*/, ''));
  const specName = `${module.code}-${suffix}.cy.js`;
  const moduleCases = cases.filter((testCase) => testCase.moduleCode === module.code);
  const testBlocks = moduleCases.map((testCase) => {
    const title = `[${testCase.id}][${testCase.moduleCode}][${testCase.priority}] ${testCase.title}`;
    return `  it(${JSON.stringify(title)}, () => {\n    cy.runWorkbookTestCase(casesById[${JSON.stringify(testCase.id)}]);\n  });`;
  }).join('\n\n');

  const specContent = `/* eslint-disable no-undef */\n// Generated by scripts/extract-cypress-testcases.mjs. Do not edit manually.\n\nimport matrix from '../../fixtures/testcase-matrix.json';\n\nconst casesById = Object.fromEntries(matrix.cases.map((testCase) => [testCase.id, testCase]));\n\ndescribe('[${module.code}] ${module.name.replace(/'/g, "\\'")} workbook cases', () => {\n  before(() => {\n    cy.resetTestData();\n  });\n\n${testBlocks}\n});\n`;
  fs.writeFileSync(path.join(excelSpecDir, specName), specContent, 'utf8');
}

console.log(`Extracted ${cases.length} Cypress test cases from ${workbookPath}`);
console.log(`Wrote ${fixturePath}`);
console.log(`Generated ${modules.length + 1} Cypress specs in ${excelSpecDir}`);
