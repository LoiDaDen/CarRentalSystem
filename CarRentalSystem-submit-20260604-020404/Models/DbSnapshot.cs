// CarRentalSystem/Models/DbSnapshot.cs
using System;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace CarRentalSystem.Models;

/// <summary>
/// Lưu trữ snapshot data của database tại một thời điểm.
/// Dùng để backup và restore dữ liệu.
/// </summary>
public class DbSnapshot
{
    [Key]
    public int SnapshotID { get; set; }

    [Required]
    [MaxLength(200)]
    public string Name { get; set; } = "";

    [MaxLength(500)]
    public string? Description { get; set; }

    /// <summary>
    /// JSON chứa toàn bộ data snapshot
    /// </summary>
    [Required]
    [Column(TypeName = "nvarchar(max)")]
    public string DataJson { get; set; } = "{}";

    /// <summary>
    /// Dung lượng JSON (bytes)
    /// </summary>
    public long DataSizeBytes { get; set; }

    /// <summary>
    /// Số lượng bảng được snapshot
    /// </summary>
    public int TableCount { get; set; }

    /// <summary>
    /// Tổng số dòng data
    /// </summary>
    public int TotalRows { get; set; }

    /// <summary>
    /// Loại snapshot: Full, Partial, BeforeMigrate
    /// </summary>
    [MaxLength(50)]
    public string SnapshotType { get; set; } = "Full";

    /// <summary>
    /// Trạng thái: Creating, Ready, Restoring, Restored, Failed, AutoDeleted
    /// </summary>
    [MaxLength(50)]
    public string Status { get; set; } = "Creating";

    [MaxLength(1000)]
    public string? ErrorMessage { get; set; }

    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

    public DateTime? RestoredAt { get; set; }

    public int? RestoredBy { get; set; }

    /// <summary>
    /// Snapshot này có phải là tự động không (scheduled)
    /// </summary>
    public bool IsAutoGenerated { get; set; } = false;

    /// <summary>
    /// Thời gian hết hạn (nếu có)
    /// </summary>
    public DateTime? ExpiresAt { get; set; }

    /// <summary>
    /// Phiên bản app khi tạo snapshot
    /// </summary>
    [MaxLength(100)]
    public string? AppVersion { get; set; }

    // Navigation
    [ForeignKey("RestoredBy")]
    public User? RestoredByUser { get; set; }

    // Computed
    public string DataSizeFormatted => DataSizeBytes switch
    {
        < 1024 => DataSizeBytes + " B",
        < 1024 * 1024 => (DataSizeBytes / 1024.0).ToString("N1") + " KB",
        < 1024 * 1024 * 1024 => (DataSizeBytes / (1024.0 * 1024)).ToString("N1") + " MB",
        _ => (DataSizeBytes / (1024.0 * 1024 * 1024)).ToString("N2") + " GB"
    };

    public bool IsExpired => ExpiresAt.HasValue && ExpiresAt.Value < DateTime.UtcNow;
}
