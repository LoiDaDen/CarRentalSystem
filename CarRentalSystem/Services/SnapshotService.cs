// CarRentalSystem/Services/SnapshotService.cs
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using System.Threading.Tasks;
using CarRentalSystem.Data;
using CarRentalSystem.Models;
using Microsoft.AspNetCore.Hosting;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.Logging;

namespace CarRentalSystem.Services;

public interface ISnapshotService
{
    Task<SnapshotResult> CreateSnapshotAsync(string name, string? description, string type = "Full", bool isAuto = false);
    Task<List<DbSnapshot>> GetAllSnapshotsAsync();
    Task<DbSnapshot?> GetSnapshotByIdAsync(int id);
    Task<SnapshotResult> RestoreSnapshotAsync(int snapshotId, int userId);
    Task CleanupExpiredSnapshotsAsync();
    Task<SnapshotResult> DeleteSnapshotAsync(int snapshotId);
}

public class SnapshotResult
{
    public bool Success { get; set; }
    public string Message { get; set; } = "";
    public int? SnapshotId { get; set; }
    public long DataSizeBytes { get; set; }
    public int TotalRows { get; set; }
}

public class SnapshotService : ISnapshotService
{
    private readonly ApplicationDbContext _context;
    private readonly ILogger<SnapshotService> _logger;
    private readonly IConfiguration _configuration;
    private readonly IWebHostEnvironment _environment;

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = false,
        DefaultIgnoreCondition = System.Text.Json.Serialization.JsonIgnoreCondition.WhenWritingNull
    };

    public SnapshotService(
        ApplicationDbContext context,
        ILogger<SnapshotService> logger,
        IConfiguration configuration,
        IWebHostEnvironment environment)
    {
        _context = context;
        _logger = logger;
        _configuration = configuration;
        _environment = environment;
    }

    public async Task<SnapshotResult> CreateSnapshotAsync(string name, string? description, string type = "Full", bool isAuto = false)
    {
        try
        {
            var snapshot = new DbSnapshot
            {
                Name = name,
                Description = description,
                SnapshotType = type,
                IsAutoGenerated = isAuto,
                Status = "Creating",
                CreatedAt = DateTime.UtcNow,
                AppVersion = GetType().Assembly.GetName().Version?.ToString() ?? "1.0"
            };

            _context.DbSnapshots.Add(snapshot);
            await _context.SaveChangesAsync();

            var data = new Dictionary<string, object>();
            int totalRows = 0;

            if (type == "Full" || type == "BeforeMigrate")
            {
                data["Areas"] = await GetTableData<Area>();
                data["AreaLocations"] = await GetTableData<AreaLocation>();
                data["AreaStaffs"] = await GetTableData<AreaStaff>();
                data["Cars"] = await GetTableData<Car>();
                data["CarModels"] = await GetTableData<CarModel>();
                data["CarAmenities"] = await GetTableData<CarAmenity>();
                data["CarAmenityMappings"] = await GetTableData<CarAmenityMapping>();
                data["CarBrands"] = await GetTableData<CarBrand>();
                data["CarStatuses"] = await GetTableData<CarStatus>();
                data["CarTypes"] = await GetTableData<CarType>();
                data["Bookings"] = await GetTableData<Booking>();
                data["BookingStatuses"] = await GetTableData<BookingStatus>();
                data["Users"] = await GetTableData<User>();
                data["Locations"] = await GetTableData<Location>();
                data["Payments"] = await GetTableData<Payment>();
                data["Promotions"] = await GetTableData<Promotion>();
                data["MembershipTiers"] = await GetTableData<MembershipTier>();
                data["Reviews"] = await GetTableData<Review>();
                data["MaintenanceLogs"] = await GetTableData<MaintenanceLog>();
                data["AddOns"] = await GetTableData<AddOn>();
                data["ContractTypes"] = await GetTableData<ContractType>();
                data["HolidayPricing"] = await GetTableData<HolidayPricing>();
                data["Routes"] = await GetTableData<Models.Route>();
                data["Invoices"] = await GetTableData<Invoice>();
                data["AuditLogs"] = await GetTableData<AuditLog>();
                data["PhysicalContractTypes"] = await GetTableData<PhysicalContractType>();
                data["PhysicalContracts"] = await GetTableData<PhysicalContract>();
                data["LongTermRentals"] = await GetTableData<LongTermRental>();
                data["HandoverRecords"] = await GetTableData<HandoverRecord>();
                data["InspectionRecords"] = await GetTableData<InspectionRecord>();
                data["VehicleTracking"] = await GetTableData<VehicleTracking>();
                data["ContactMessages"] = await GetTableData<ContactMessage>();
                data["Wallets"] = await GetTableData<Wallet>();
                data["WalletTransactions"] = await GetTableData<WalletTransaction>();
                data["CartItems"] = await GetTableData<CartItem>();
                data["AlertLogs"] = await GetTableData<Alert>();
                data["CarImages"] = await GetTableData<CarImage>();
                data["BookingAddOns"] = await GetTableData<BookingAddOn>();
                data["PaymentSchedules"] = await GetTableData<PaymentSchedule>();
                data["AvailabilitySchedules"] = await GetTableData<AvailabilitySchedule>();
                data["DynamicPricingRules"] = await GetTableData<DynamicPricingRule>();

                foreach (var table in data.Values)
                {
                    if (table is List<object> rows)
                        totalRows += rows.Count;
                }
            }
            else if (type == "Partial")
            {
                data["Bookings"] = await GetTableData<Booking>();
                data["Payments"] = await GetTableData<Payment>();
                data["Cars"] = await GetTableData<Car>();
                data["Users"] = await GetTableData<User>();
                data["Locations"] = await GetTableData<Location>();

                foreach (var table in data.Values)
                {
                    if (table is List<object> rows)
                        totalRows += rows.Count;
                }
            }

            var json = JsonSerializer.Serialize(data, JsonOptions);
            var bytes = System.Text.Encoding.UTF8.GetBytes(json);

            snapshot.DataJson = json;
            snapshot.DataSizeBytes = bytes.Length;
            snapshot.TotalRows = totalRows;
            snapshot.TableCount = data.Count;
            snapshot.Status = "Ready";

            await _context.SaveChangesAsync();

            _logger.LogInformation("Snapshot '{Name}' created successfully. Size: {Size}, Rows: {Rows}",
                name, snapshot.DataSizeFormatted, totalRows);

            return new SnapshotResult
            {
                Success = true,
                Message = $"Snapshot '{name}' đã được tạo thành công. Kích thước: {snapshot.DataSizeFormatted}, {totalRows} dòng dữ liệu.",
                SnapshotId = snapshot.SnapshotID,
                DataSizeBytes = bytes.Length,
                TotalRows = totalRows
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to create snapshot '{Name}'", name);
            return new SnapshotResult
            {
                Success = false,
                Message = "Lỗi khi tạo snapshot: " + ex.Message
            };
        }
    }

    private async Task<List<object>> GetTableData<T>() where T : class
    {
        try
        {
            var query = _context.Set<T>().AsQueryable();

            if (typeof(T) == typeof(AuditLog))
            {
                return (await query.AsNoTracking().IgnoreQueryFilters().ToListAsync())
                    .Cast<object>().ToList();
            }

            if (typeof(T) == typeof(MaintenanceLog))
            {
                return (await query.AsNoTracking().IgnoreQueryFilters().ToListAsync())
                    .Cast<object>().ToList();
            }

            if (typeof(T) == typeof(AreaStaff))
            {
                return (await query.AsNoTracking().IgnoreQueryFilters().ToListAsync())
                    .Cast<object>().ToList();
            }

            if (typeof(T) == typeof(AreaLocation))
            {
                return (await query.AsNoTracking().IgnoreQueryFilters().ToListAsync())
                    .Cast<object>().ToList();
            }

            if (typeof(T) == typeof(Area))
            {
                return (await query.AsNoTracking().IgnoreQueryFilters().ToListAsync())
                    .Cast<object>().ToList();
            }

            return (await query.AsNoTracking().ToListAsync()).Cast<object>().ToList();
        }
        catch
        {
            return new List<object>();
        }
    }

    public async Task<List<DbSnapshot>> GetAllSnapshotsAsync()
    {
        return await _context.DbSnapshots
            .OrderByDescending(s => s.CreatedAt)
            .ToListAsync();
    }

    public async Task<DbSnapshot?> GetSnapshotByIdAsync(int id)
    {
        return await _context.DbSnapshots.FindAsync(id);
    }

    public async Task<SnapshotResult> RestoreSnapshotAsync(int snapshotId, int userId)
    {
        if (_environment.IsProduction() && !_configuration.GetValue("Snapshot:AllowUnsafeRestore", false))
        {
            _context.AuditLogs.Add(new AuditLog
            {
                Action = "SnapshotRestoreBlocked",
                EntityType = "DbSnapshot",
                EntityId = snapshotId,
                UserId = userId == 0 ? null : userId,
                Description = "Unsafe JSON snapshot restore is disabled in Production.",
                Timestamp = DateTime.UtcNow
            });
            await _context.SaveChangesAsync();
            return new SnapshotResult
            {
                Success = false,
                Message = "Snapshot restore is disabled in Production. Use managed database point-in-time restore."
            };
        }

        var snapshot = await _context.DbSnapshots
            .FirstOrDefaultAsync(s => s.SnapshotID == snapshotId);

        if (snapshot == null)
            return new SnapshotResult { Success = false, Message = "Snapshot không tồn tại." };

        if (snapshot.Status != "Ready")
            return new SnapshotResult { Success = false, Message = $"Snapshot đang ở trạng thái '{snapshot.Status}', không thể restore." };

        try
        {
            snapshot.Status = "Restoring";
            await _context.SaveChangesAsync();

            var data = JsonSerializer.Deserialize<Dictionary<string, JsonElement>>(snapshot.DataJson);
            if (data == null)
            {
                snapshot.Status = "Ready";
                snapshot.ErrorMessage = "Không thể đọc dữ liệu JSON.";
                await _context.SaveChangesAsync();
                return new SnapshotResult { Success = false, Message = "Dữ liệu snapshot không hợp lệ." };
            }

            var tables = data.Keys.ToList();
            var tablesRestored = 0;
            var rowsRestored = 0;

            foreach (var tableName in tables)
            {
                var (success, count) = await RestoreTableAsync(tableName, data[tableName]);
                if (success)
                {
                    tablesRestored++;
                    rowsRestored += count;
                }
            }

            snapshot.Status = "Restored";
            snapshot.RestoredAt = DateTime.UtcNow;
            snapshot.RestoredBy = userId;
            await _context.SaveChangesAsync();

            _logger.LogInformation("Snapshot '{Name}' restored by user {UserId}. Tables: {Tables}, Rows: {Rows}",
                snapshot.Name, userId, tablesRestored, rowsRestored);

            return new SnapshotResult
            {
                Success = true,
                Message = $"Đã restore snapshot '{snapshot.Name}'. Đã khôi phục {tablesRestored} bảng, {rowsRestored} dòng dữ liệu.",
                SnapshotId = snapshotId,
                TotalRows = rowsRestored
            };
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to restore snapshot {Id}", snapshotId);
            snapshot.Status = "Failed";
            snapshot.ErrorMessage = ex.Message;
            await _context.SaveChangesAsync();
            return new SnapshotResult { Success = false, Message = "Lỗi khi restore snapshot: " + ex.Message };
        }
    }

    private async Task<(bool Success, int RowsRestored)> RestoreTableAsync(string tableName, JsonElement data)
    {
        try
        {
            var rows = data.EnumerateArray().ToList();
            if (rows.Count == 0) return (true, 0);

            var entityType = tableName switch
            {
                "Areas" => typeof(Area),
                "AreaLocations" => typeof(AreaLocation),
                "AreaStaffs" => typeof(AreaStaff),
                "Cars" => typeof(Car),
                "CarModels" => typeof(CarModel),
                "CarAmenities" => typeof(CarAmenity),
                "CarAmenityMappings" => typeof(CarAmenityMapping),
                "CarBrands" => typeof(CarBrand),
                "CarStatuses" => typeof(CarStatus),
                "CarTypes" => typeof(CarType),
                "Bookings" => typeof(Booking),
                "BookingStatuses" => typeof(BookingStatus),
                "Users" => typeof(User),
                "Locations" => typeof(Location),
                "Payments" => typeof(Payment),
                "Promotions" => typeof(Promotion),
                "MembershipTiers" => typeof(MembershipTier),
                "Reviews" => typeof(Review),
                "MaintenanceLogs" => typeof(MaintenanceLog),
                "AddOns" => typeof(AddOn),
                "ContractTypes" => typeof(ContractType),
                "HolidayPricing" => typeof(HolidayPricing),
                "Routes" => typeof(Models.Route),
                "Invoices" => typeof(Invoice),
                "AuditLogs" => typeof(AuditLog),
                "PhysicalContractTypes" => typeof(PhysicalContractType),
                "PhysicalContracts" => typeof(PhysicalContract),
                "LongTermRentals" => typeof(LongTermRental),
                "HandoverRecords" => typeof(HandoverRecord),
                "InspectionRecords" => typeof(InspectionRecord),
                "VehicleTracking" => typeof(VehicleTracking),
                "ContactMessages" => typeof(ContactMessage),
                "Wallets" => typeof(Wallet),
                "WalletTransactions" => typeof(WalletTransaction),
                "CartItems" => typeof(CartItem),
                "AlertLogs" => typeof(Alert),
                "CarImages" => typeof(CarImage),
                "BookingAddOns" => typeof(BookingAddOn),
                "PaymentSchedules" => typeof(PaymentSchedule),
                "AvailabilitySchedules" => typeof(AvailabilitySchedule),
                "DynamicPricingRules" => typeof(DynamicPricingRule),
                _ => (Type?)null
            };

            if (entityType == null) return (true, 0);

            var dbSet = _context.GetType()
                .GetMethod("Set", Type.EmptyTypes)!
                .MakeGenericMethod(entityType)
                .Invoke(_context, null);

            var addMethod = dbSet!.GetType().GetMethod("Add");
            var saveAsyncMethod = typeof(ApplicationDbContext).GetMethod("SaveChangesAsync")!;

            int added = 0;
            foreach (var row in rows)
            {
                try
                {
                    var entity = JsonSerializer.Deserialize(row.GetRawText(), entityType);
                    if (entity != null)
                    {
                        addMethod!.Invoke(dbSet, new[] { entity });
                        added++;
                    }
                }
                catch { }
            }

            if (added > 0)
                await (Task<int>)saveAsyncMethod.Invoke(_context, null)!;

            return (true, added);
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "Failed to restore table {Table}", tableName);
            return (false, 0);
        }
    }

    public async Task CleanupExpiredSnapshotsAsync()
    {
        var expired = await _context.DbSnapshots
            .Where(s => s.ExpiresAt != null && s.ExpiresAt < DateTime.UtcNow)
            .ToListAsync();

        foreach (var s in expired)
        {
            s.Status = "AutoDeleted";
        }

        await _context.SaveChangesAsync();
        _logger.LogInformation("Cleaned up {Count} expired snapshots", expired.Count);
    }

    public async Task<SnapshotResult> DeleteSnapshotAsync(int snapshotId)
    {
        var snapshot = await _context.DbSnapshots.FindAsync(snapshotId);
        if (snapshot == null)
            return new SnapshotResult { Success = false, Message = "Snapshot không tồn tại." };

        _context.DbSnapshots.Remove(snapshot);
        await _context.SaveChangesAsync();

        return new SnapshotResult
        {
            Success = true,
            Message = $"Đã xóa snapshot '{snapshot.Name}'."
        };
    }
}
